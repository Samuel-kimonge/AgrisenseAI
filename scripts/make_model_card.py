"""Generate reports/model_cards/tomato_classifier.md and DATASET.md numbers from REAL training outputs."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from config import get_settings


def main() -> None:
    s = get_settings()
    meta = json.loads((s.production_model_dir / "metadata.json").read_text())
    ev = s.reports_dir / "evaluation"
    test = json.loads((ev / "test_report.json").read_text())
    val = json.loads((ev / "val_report.json").read_text())
    ds = json.loads((s.processed_dir / "validation_report.json").read_text())
    ood = json.loads((ev / "ood_report.json").read_text()) if (ev / "ood_report.json").exists() else None
    t = meta["training"]
    rows = "\n".join(f"| {k} | {v['precision']:.3f} | {v['recall']:.3f} | {v['f1-score']:.3f} | {int(v['support'])} |"
                     for k, v in test["classification_report"].items() if k in meta["class_keys"])
    card = f"""# Model card: Tomato leaf condition classifier

*Generated by `scripts/make_model_card.py` from the actual training outputs. Do not edit numbers by hand.*

- **Version:** {meta['model_version']}  (trained {meta['trained_at'][:10]})
- **Architecture:** {meta['architecture']}
- **Input:** RGB leaf photo resized to {meta['image_size']}x{meta['image_size']}
- **Classes ({len(meta['class_keys'])}):** {', '.join(meta['class_keys'])}
- **Libraries:** {meta['libraries']}

## Training
- Transfer learning from ImageNet weights; head-only stage then full fine-tuning (AdamW, one-cycle schedule, label smoothing 0.05).
- Augmentation: random resized crop, flips, rotation, colour jitter.
- Training images per class capped at {t['train_cap_per_class']} (CPU-only machine): n_train={t['n_train']}, n_val={t['n_val']} (cap {t['val_cap_per_class']}/class), n_test={t['n_test']} (full held-out split).
- Epochs run: {t['epochs_run']} (resumed from epoch {t.get('resumed_from_epoch')} after an interrupted run)  | seed {t['seed']}
- Split: stratified 70/15/15 on {ds['total_kept']} validated images (exact duplicates removed: {ds['problems'].get('exact_duplicate', 0)}).

## Held-out test results (n={test['n']}, never used for training, calibration or threshold selection)
| Metric | Value |
|---|---|
| Accuracy (all images, no abstention) | {test['accuracy']:.4f} |
| Macro F1 | {test['macro_f1']:.4f} |
| Weighted F1 | {test['weighted_f1']:.4f} |
| ECE before / after temperature scaling | {test['ece_uncalibrated']:.4f} / {test['ece_calibrated']:.4f} |
| Coverage at abstention thresholds | {test['coverage_at_thresholds']:.3f} |
| Accuracy among answered images | {test['selective_accuracy']:.4f} |

Per-class (test):

| Class | Precision | Recall | F1 | Support |
|---|---|---|---|---|
{rows}

Confusion matrix: `reports/evaluation/confusion_matrix.csv`. Full report: `reports/evaluation/test_report.json`.

## Calibration and abstention
- Temperature T = {meta['temperature']:.3f} fitted on the validation split. Thresholds (chosen on validation only): {meta['thresholds']}.
- The system abstains when calibrated confidence, margin between the top two classes, or the raw maximum logit is too low, and rejects blurry, dark, tiny or non-leaf photos before classification.
"""
    if ood:
        card += f"""
## Out-of-scope check
{ood['note']} Sample n={ood['n']}: the system abstained on {ood['abstained']} ({ood['abstention_rate']:.1%}); mean confidence on these leaves was {ood['mean_confidence']:.2f}.
This means **{(1 - ood['abstention_rate']):.1%} of other-crop leaves would still receive a tomato label**, so the crop selector and user instructions matter. See limitations.
"""
    card += """
## Intended use
Preliminary screening of single tomato-leaf photos to help farmers decide whether to seek expert help. **Not** a diagnostic device.

## Limitations (read before use)
1. **Controlled-environment data.** PlantVillage photos have uniform backgrounds and lighting. Field performance (clutter, shadows, hands, other cultivars, multiple simultaneous problems) is **not measured** here and is expected to be lower. Field validation with local photos labelled by plant pathologists is required.
2. **Possible optimistic test scores.** A random split can put near-identical photos of the same leaf in train and test. Test accuracy should be read as an upper bound.
3. **Calibration is in-distribution only.** Confidence on real-world photos can be overconfident.
4. **Look-alike conditions** (early blight vs target spot; viruses vs herbicide/nutrient damage) are inherently confusable from one leaf photo.
5. **Out-of-distribution detection is imperfect** (see above). Only tomato leaves are supported.
6. Trained on a reduced, class-capped subset for speed on a CPU; a longer run on all images would likely improve results.
"""
    out = s.reports_dir / "model_cards" / "tomato_classifier.md"
    out.write_text(card)
    print("Wrote", out)


if __name__ == "__main__":
    main()
